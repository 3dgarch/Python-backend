numero1 = 10
numero2 = 5

# Suma +
print("Suma:", numero1 + numero2)

# Resta -
print("Resta:", numero1 - numero2)

# Multiplicación *
print("Multiplicación:", numero1 * numero2)

# División /
print("División:", numero1 / numero2)

# Módulo %
print("Módulo:", numero1 % numero2)

# Cociente //
print("Cociente:", numero1 // numero2)




